            charge.OperationalPeriodId,
            charge.OperationalPeriodName,
            charge.BillingMonth,
            charge.ChargeTypeId,
            charge.ChargeTypeName,
            charge.ChargeFrequency,
            charge.StudentId,
            charge.StudentName,
            charge.StudentNis,
            charge.SchoolLevel,
            charge.Grade,
            charge.StudyGroupId,
            charge.StudyGroupName,
            charge.Description,
            charge.UnitAmount,
            charge.Quantity,
            charge.GrossAmount,
            charge.DiscountAmount,
            charge.DiscountReason,
            charge.NetAmount,
            charge.PaidAmount,
            charge.OutstandingAmount,
            charge.Status,
            charge.DueDate,
            charge.CancellationReason,
            charge.CancelledAt,
            charge.CreatedAt,
            charge.UpdatedAt);
